package com.ava.proto.data

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.ava.proto.capture.Channel

/**
 * 판정을 등급으로 접은 값. 기본 경로는 모델 서버가 준 [EventEntity.risk]와
 * [EventEntity.stage]를 함께 보고 정하고, 서버 주소가 없을 때만 키워드 대역이 만든다
 * (그쪽은 `HIGH`/`NONE` 둘뿐이다).
 *
 * 화면에 나가는 이름과 여기 상수가 다섯 갈래로 일치한다 — 정상 · 예보 · 주의보 ·
 * 경보우려 · 경보.
 *
 * [HIGH_UNBACKED]를 잠깐 [HIGH] 안에서 `stage == null`로 갈라 부르기만 했었다. 위험도 90
 * 위에서는 단계가 없어도 경보로 부르기로 하면서 그 방식이 깨졌다 — 화면이 등급 이름을
 * 정하려면 위험도 문턱을 UI가 다시 재야 하는데, **문턱은 판정 계층 한 곳에만 있어야 한다.**
 * 그래서 상수로 갈랐다. 이후 문턱이 또 움직여도 UI는 이름만 붙인다.
 */
enum class RiskSignal {
    NONE,

    /**
     * 예보 — 모델이 애매하다고 봤고(33~66) 규칙도 아무 단계를 못 찾은 상태.
     *
     * 예전에는 이 구간을 [NONE]으로 접어 화면에서 아예 뺐다. 이름을 준 이유는 이 자리가
     * **비어 있는 자리가 아니라 섞여 있는 자리**여서다 — 실측에서 정상 6건(퇴직연금 상담
     * 51.0, 부동산 잔금일정 47.0 등)과 피싱 3건(가족사칭 48.0 등)이 함께 들어왔다.
     * 정상으로 단정하면 그 피싱 3건이 기록에서 사라진다.
     *
     * **알림은 나간다.** 등급 이름이 붙은 것은 여기까지 전부 알린다 — 판정기 어느 쪽도
     * 확신하지 않은 구간이라 정상 통화도 함께 울리지만, 미탐은 돈이 나가고 오탐은 짜증에
     * 그친다. 걸러내는 것은 [NONE]뿐이다([com.ava.proto.session.SessionEngine]).
     */
    FORECAST,

    /**
     * 주의보 — 모델은 애매하다고 했지만(33~66) 규칙이 진행 단계를 찾아낸 상태.
     *
     * 예전 이름은 `LOW`였고 위험도 40~70 구간에 붙었는데, **읽는 코드가 한 곳도 없어
     * 사실상 죽은 값이었다.** 두 판정기가 겹칠 때만 켜지는 등급으로 되살렸다.
     */
    CAUTION,

    /**
     * 경보우려 — 위험도 66~90인데 규칙이 진행 단계를 하나도 못 찾은 상태.
     *
     * 모델만 위험하다고 본 자리라 말로는 단정하지 않는다. 정상 통화가 위험도 99.0을 받은
     * 일이 실제로 있었다. **그래도 [HIGH]와 똑같이 알림이 나가고 세션에도 들어간다** —
     * 규칙이 신호를 못 찾는 피싱이 검증셋 기준 19%나 되므로, 알리지 않으면 그만큼이
     * 통째로 빠진다. 낮춘 것은 부르는 이름과 색이지 대응이 아니다.
     */
    HIGH_UNBACKED,

    /**
     * 경보 — 두 판정기가 겹쳤거나(66 이상 + 단계), 모델 혼자서 단정할 만큼 높은 구간(90 이상).
     *
     * 90 위에서 단계를 안 보는 이유는 그 위가 **규칙이 실패하는 자리이기도 하기 때문이다** —
     * 백테스트 100건에서 90 이상 + 단계 없음 4건이 전부 실제 피싱이었다(투자사기·은행사칭·
     * 기관사칭·카드사사칭). 규칙이 못 따라온 것이지 모델이 틀린 것이 아니었다.
     */
    HIGH,
}

enum class EventStatus {
    /** 텍스트까지 확보되어 분석이 끝난 상태 (SMS/카톡은 캡처 즉시 이 상태). */
    ANALYZED,

    /**
     * 원본은 있는데 텍스트가 없는 상태. 서버 주소가 없어 전사를 아예 하지 않았거나,
     * 전사를 시도했다 실패한 경우다. [EventDao.analyzedSourceLabels]가 이 상태를 제외하므로
     * 다음 스캔에서 다시 시도된다.
     */
    PENDING_TRANSCRIPTION,

    /**
     * 텍스트는 있었지만 분류 호출 자체가 실패한 상태 (네트워크 오류 등).
     * [RiskSignal.NONE]과 구분해서 기록한다 — NONE은 "분류해봤더니 무해함"이라는 뜻이지,
     * "분류를 못 함"이라는 뜻이 아니다. 이 상태가 없으면 실패를 NONE으로 뭉개게 되어
     * 게이트 시절의 모호함("NONE = 분석 안 됨")이 조용히 되돌아온다.
     */
    CLASSIFICATION_FAILED,
}

@Entity(tableName = "events")
data class EventEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val channel: Channel,
    /** SMS/카톡은 알림 시각, 통화 녹음은 파일의 마지막 수정 시각. */
    val capturedAt: Long,
    /** 알림 발신 패키지명 또는 녹음 파일명. */
    val sourceLabel: String,
    val text: String?,
    val status: EventStatus,
    val riskSignal: RiskSignal,
    val matchedPhrase: String?,
    val sessionId: Long?,
    /**
     * 음성 파일의 SAF URI. 통화 채널에서만, 그중에서도 실제 녹음일 때만 채워진다
     * (`.txt` 전사본은 재생할 오디오가 없어 null).
     *
     * **읽는 코드는 아직 없다** — 앱에 재생 화면이 없기 때문이다. 그래도 남기는 이유는
     * 오판을 되짚을 때 "그 판정이 어느 파일에서 나왔나"를 아는 유일한 값이라서다.
     * [sourceLabel]은 파일명뿐이라 폴더를 바꾸면 같은 이름이 겹칠 수 있다.
     */
    val audioUri: String? = null,
    /**
     * 상대방 식별자 (SMS/카톡은 알림의 발신자 제목, 통화는 발신번호를 알 방법이 없어 항상 null —
     * READ_CALL_LOG를 쓰지 않기로 한 결정 때문에 이 채널만 식별자가 비어 있다).
     * 세션 융합이 시간 창만으로 무관한 상대를 섞어버리지 않도록 이 값으로 스코프를 좁힌다.
     */
    val counterpart: String? = null,
    /**
     * 모델이 매긴 0~100 위험도. 백엔드 판정 경로에서만 채워진다.
     *
     * [riskSignal]은 이 값을 세 단계로 접은 것이라 87점과 100점을 구분하지 못한다.
     * 원본을 따로 남기는 이유는 그것이 **보정된 확률**이기 때문이다 — 검증셋에서 ECE 0.006으로
     * 확인했듯 87점은 실제로 87% 확률을 뜻한다. 접어버리면 그 정보가 사라진다.
     */
    val risk: Double? = null,
    /**
     * 사기 진행 단계 1~3과 그 이름. 위험도와 **다른 값**이다 — 위험도가 "피싱이 맞나"라면
     * 이건 "지금 어디까지 왔나"다. 같은 99%라도 1단계(겁주기만)와 3단계(송금 지시)는
     * 사용자가 해야 할 행동이 다르다. 화면에 나가는 것은 이 값이다.
     */
    val stage: Int? = null,
    val stageLabel: String? = null,
)
